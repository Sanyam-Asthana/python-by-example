# Ends with a new-line character by default
print("Hello!")

# Change the ending character (default is '\n')
print("Hello", end="!")

# Empty print() to print a newline
print()

# Print numbers
print(2)
print(4 * 9)

# Concatenate strings (separated by a space by default)
print("I am", 18, "years old")

# Change the separating character
print("Apple", "Banana", "Orange", sep=", ", end="!")
