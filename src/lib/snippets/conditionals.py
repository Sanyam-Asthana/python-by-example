x = 5
# If Condition
if x > 3:
    print("x is greater than 3")

# If-else Condition
if x > 6:
    print("x is greater than 6")
else:
    print("x is not greater than 6")

# If-elif-else Condition
if x > 6:
    print("x is greater than 6")
elif x == 5:
    print("x is equal to 5")
else:
    print("x is less than 5")
